from __future__ import annotations

import hashlib
import typing as t
from dataclasses import dataclass, field
from functools import cached_property

# Bump to force every engine to reload the dataset, e.g. after changing how tables are loaded
LOADER_VERSION = 1


@dataclass(frozen=True)
class Column:
    """
    A dataset column. `types` maps an engine name to the column's physical type on that engine.

    Physical types are written by hand rather than generated by sqlglot: if sqlglot's type mapping
    were wrong, a generated schema would silently store different data on each engine.
    """

    name: str
    types: dict[str, str]
    # CHAR(n) values are read back padded to n characters
    char_length: int | None = None


@dataclass
class Table:
    name: str
    columns: list[Column]
    build_rows: t.Callable[[], list[tuple]] = field(repr=False)
    description: str = ""

    @property
    def engines(self) -> set[str]:
        """The engines that have this table, i.e. those that every column has a type for."""
        return set.intersection(*(set(column.types) for column in self.columns))

    @cached_property
    def rows(self) -> list[tuple]:
        rows = self.build_rows()
        width = len(self.columns)
        for row in rows:
            if len(row) != width:
                raise ValueError(f"{self.name}: row {row!r} doesn't have {width} values")
        return rows

    @cached_property
    def fingerprint(self) -> str:
        """Changes whenever the table's definition or data changes, which triggers a reload."""
        digest = hashlib.sha256(f"{LOADER_VERSION}|{self.name}".encode())
        for column in self.columns:
            digest.update(repr((column.name, sorted(column.types.items()))).encode())
        for row in self.rows:
            digest.update(repr(row).encode())
        return digest.hexdigest()

    def expected_rows(self) -> list[tuple]:
        """The rows as an engine is expected to return them."""
        lengths = [column.char_length for column in self.columns]
        if not any(lengths):
            return self.rows
        return [
            tuple(
                value.ljust(length) if length and isinstance(value, str) else value
                for value, length in zip(row, lengths)
            )
            for row in self.rows
        ]


def column(
    name: str,
    *,
    postgres: str | None = None,
    spark: str | None = None,
    char_length: int | None = None,
) -> Column:
    types = {engine: ddl for engine, ddl in (("postgres", postgres), ("spark", spark)) if ddl}
    return Column(name, types, char_length)


def shared(name: str, postgres: str, spark: str, char_length: int | None = None) -> Column:
    """A column that exists on every engine."""
    return column(name, postgres=postgres, spark=spark, char_length=char_length)
